#!/usr/bin/env python3
"""Write a static, crawlable list of every trail into the five dashboards.

Why this exists
---------------
The dashboard builds its trail cards client-side (`dashboard.js` sets
`#trailBoard.innerHTML`), so in the raw HTML that Googlebot reads first, the
hub linked to *nothing*. The whole site's static link graph was `/` <-> the
four `/trails/` pages -- and Search Console duly reported knowing 4 URLs out of
the 164 in the sitemap. The 36 spoke pages had no HTML path leading to them.

So: emit a real `<a href>` per trail inside `#trailBoard`, between marker
comments. Crawlers and no-JS visitors get a working index; `dashboard.js`
overwrites the whole container on load, so JS visitors never see it.

Re-runnable and idempotent -- run it again whenever `status.json` gains or
loses a trail:

    python scripts/gen_trail_index.py
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

START = "<!-- STATIC-TRAIL-INDEX:START (generated by scripts/gen_trail_index.py) -->"
END = "<!-- STATIC-TRAIL-INDEX:END -->"

# Heading above the static list, per language. Only ever seen by crawlers and
# no-JS visitors -- dashboard.js replaces the container on a successful load.
LANGS = {
    "": "All Madeira PR trails",
    "pt": "Todos os percursos PR da Madeira",
    "fr": "Tous les sentiers PR de Madère",
    "de": "Alle PR-Wanderwege Madeiras",
    "pl": "Wszystkie szlaki PR na Maderze",
}


def localise(page: str, lang: str) -> str:
    """Map an English spoke path onto its `pt/`, `fr/`, `de/` or `pl/` twin."""
    if not lang:
        return page
    return f"/{lang}{page}"


# Status word after each link (2026-10-05), so a crawler that doesn't run dashboard.js still
# sees every trail's status. Filled here from status.json and refreshed daily by
# update_status.py (same words as the STATIC-STATUS lines).
STATUS_WORD = {
    "": {"OPEN": "OPEN", "PARTIAL": "PARTLY OPEN", "CLOSED": "CLOSED"},
    "pt": {"OPEN": "ABERTO", "PARTIAL": "PARCIALMENTE ABERTO", "CLOSED": "ENCERRADO"},
    "fr": {"OPEN": "OUVERT", "PARTIAL": "PARTIELLEMENT OUVERT", "CLOSED": "FERMÉ"},
    "de": {"OPEN": "GEÖFFNET", "PARTIAL": "TEILWEISE GEÖFFNET", "CLOSED": "GESCHLOSSEN"},
    "pl": {"OPEN": "OTWARTY", "PARTIAL": "CZĘŚCIOWO OTWARTY", "CLOSED": "ZAMKNIĘTY"},
}


def badge(t: dict, lang: str) -> str:
    word = STATUS_WORD[lang].get(t.get("status"), "")
    return "<!-- STATIC-BADGE:{c}:START -->{w}<!-- STATIC-BADGE:{c}:END -->".format(
        c=t["code"], w=": " + word if word else "")


def block(trails: list, lang: str) -> str:
    items = "\n".join(
        '      <li><a href="{}">{} — {}</a>{}</li>'.format(
            localise(t["page"], lang), t["code"], t["name"], badge(t, lang)
        )
        for t in trails
    )
    return (
        f"{START}\n"
        f'    <nav class="tindex" aria-label="{LANGS[lang]}">\n'
        f"      <h2>{LANGS[lang]}</h2>\n"
        f"      <ul>\n{items}\n      </ul>\n"
        "    </nav>\n"
        f"    {END}"
    )


def main() -> None:
    trails = json.loads((ROOT / "status.json").read_text())["trails"]
    missing = [t["code"] for t in trails if not t.get("page")]
    if missing:
        sys.exit(f"FATAL: trails with no page, cannot link them: {missing}")

    for lang in LANGS:
        path = ROOT / lang / "index.html" if lang else ROOT / "index.html"
        if not path.exists():
            # e.g. pt/index.html before the Portuguese hub is written -- re-run later.
            print(f"{path.relative_to(ROOT)}: missing, skipped (re-run once it exists)")
            continue
        html = path.read_text()
        new = block(trails, lang)

        if START in html:
            html = re.sub(
                re.escape(START) + r".*?" + re.escape(END), new, html, flags=re.S
            )
        else:
            # First run: append the block inside the existing #trailBoard, after
            # the "Loading trails…" placeholder, leaving that placeholder alone.
            m = re.search(r'(<div id="trailBoard">)(.*?)(</div>)', html, flags=re.S)
            if not m:
                sys.exit(f"FATAL: #trailBoard container not found in {path}")
            html = (
                html[: m.end(2)] + "\n    " + new + "\n  " + html[m.start(3):]
            )

        path.write_text(html)
        print(f"{path.relative_to(ROOT)}: {len(trails)} trail links")


if __name__ == "__main__":
    main()
