"""Inject the site-wide navigation into every page: a top nav bar, breadcrumbs
(visible + BreadcrumbList JSON-LD), a "Nearby trails" block on each trail and a
"More guides" block of descriptive links to the guide pages.

Why this exists
---------------
A Screaming Frog crawl (2026-09-28) showed the static link graph was too thin:
the fees and booking-from-abroad pages were reachable only from each other (8
orphans), most spokes had just 5 inbound links (4 language switchers + the
board), and trail pages had no route to their neighbours. This script gives
every page the same crawlable links, all as plain `<a href>` in the raw HTML.

Four marker-delimited blocks, replaced in place on every run (idempotent):

  SITE-NAV-HEAD     before </head>   CSS + BreadcrumbList JSON-LD
  SITE-NAV          in <header>      nav bar + breadcrumb trail
  SITE-NAV-RELATED  before <footer>  4 nearest trails (trail pages only)
  SITE-NAV-GUIDES   before <footer>  "More guides": links to the pages in GUIDES that the
                                     page's own copy doesn't already link (RELATED_GUIDES
                                     picks them per page; the homepage lists all). Empty
                                     markers placed by hand (homepages) keep their spot.

"Nearby" is real distance between trailheads, from the coordinates embedded in
the Visit Madeira hiking index (the same source `update_status.py` parses).
Fails loud if that index can't be read.

Re-run after `gen_spokes.py` (which calls this itself) or whenever a trail or
page is added:

    python scripts/gen_site_nav.py
"""

