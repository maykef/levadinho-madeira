def trail_coords():
    """code -> (lat, lon) of each trailhead, from the Visit Madeira index."""
    r = requests.get(TRAILS_INDEX, headers=UA, timeout=30)
    r.raise_for_status()
    out = {}
    for m in TRAIL_RE.finditer(r.text):
        try:
            raw = json.loads('"' + m.group(1) + '"')
        except Exception:
            raw = m.group(1)
        code = (raw.split(" - ", 1)[0] if " - " in raw else raw).replace(" ", "")
        out.setdefault(code, (float(m.group(2)), float(m.group(3))))
    return out


def km(a, b):
    """Great-circle distance in km."""
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(h))


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def href(lang, path):
    """Root-relative URL of `path` (an English path) in `lang`'s folder."""
    return PREFIX[lang] + path


def file_for(lang, path):
    rel = path.lstrip("/")
    rel = rel + "index.html" if rel.endswith("/") or rel == "" else rel
    return ROOT / PREFIX[lang].lstrip("/") / rel if PREFIX[lang] else ROOT / rel


def replace_block(html, key, body, anchor_re, where, path):
    """Put `body` between `key`'s markers: in place if present, otherwise
    before/after the first match of `anchor_re`."""
    start, end = MARK[key]
    block = "{}\n{}\n{}".format(start, body, end)
    if start in html:
        return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, html, count=1, flags=re.S)
    m = re.search(anchor_re, html, flags=re.S)
    if not m:
        sys.exit("FATAL: anchor {!r} for {} not found in {}".format(anchor_re, key, path))
    i = m.start() if where == "before" else m.end()
    return html[:i] + block + "\n" + html[i:]


def nav_html(lang, current, crumbs):
    items = "\n".join(
        '    <a href="{}"{}>{}</a>'.format(href(lang, p), ' aria-current="page"' if k == current else "", esc(lbl[lang]))
        for k, p, lbl in NAV
    )
    out = '  <nav class="sitenav" aria-label="{}">\n{}\n  </nav>'.format(NAV_ARIA[lang], items)
    if crumbs:
        lis = []
        for i, (name, url) in enumerate(crumbs):
            if i == len(crumbs) - 1:
                lis.append('      <li aria-current="page">{}</li>'.format(esc(name)))
            else:
                lis.append('      <li><a href="{}">{}</a></li>'.format(url, esc(name)))
        out += '\n  <nav class="crumbs" aria-label="{}">\n    <ol>\n{}\n    </ol>\n  </nav>'.format(
            CRUMB_ARIA[lang], "\n".join(lis))
    return out


def head_html(crumbs):
    if not crumbs:
        return CSS
    ld = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i + 1, "name": name, "item": BASE + url}
            for i, (name, url) in enumerate(crumbs)
        ],
    }
    return CSS + '\n<script type="application/ld+json">\n{}\n</script>'.format(
        json.dumps(ld, ensure_ascii=False, indent=2))


def related_html(lang, near):
    items = "\n".join(
        '    <li><a href="{}">{} {}<span>{}</span></a></li>'.format(
            href(lang, t["page"]), esc(t["code"]), esc(t["name"]), dist_label(lang, d))
        for t, d in near
    )
    return ('<section class="related" id="nearby">\n  <h2>{}</h2>\n  <p>{}</p>\n  <ul>\n{}\n  </ul>\n</section>'
            .format(NEARBY[lang], NEARBY_SUB[lang], items))


def guides_html(lang, keys, html):
    """The "More guides" block: descriptive links to the guide pages in `keys`, minus the
    ones the page already links to outside the generated blocks. None if too few remain."""
    body = html
    for k in MARK:
        start, end = MARK[k]
        body = re.sub(re.escape(start) + r".*?" + re.escape(end), "", body, flags=re.S)
    body = re.sub(r"<!--\s*LEVADINHO-CTA:START.*?LEVADINHO-CTA:END\s*-->", "", body, flags=re.S)
    linked = set(re.findall(r'<a\b[^>]*href="([^"#?]+)', body))
    keys = [k for k in keys if href(lang, GUIDE[k][1]) not in linked]
    if len(keys) < N_GUIDES_MIN:
        return None
    items = "\n".join('    <li><a href="{}">{}</a></li>'.format(href(lang, GUIDE[k][1]), esc(GUIDE[k][4][lang])) for k in keys)
    return '<nav class="guides" aria-label="{0}">\n  <h2>{0}</h2>\n  <ul>\n{1}\n  </ul>\n</nav>'.format(GUIDES_H[lang], items)


def drop_block(html, key):
    start, end = MARK[key]
    return re.sub(r"\n?" + re.escape(start) + r".*?" + re.escape(end), "", html, flags=re.S)


SKIPPED = []


def process(path, lang, current, crumbs, near=None, guides=None,
            header_anchor=r'<nav class="langs"[^>]*>.*?</nav>\n'):
    if not path.exists():
        # A language's page may not exist yet -- skip it and say so; re-run once the file is there.
        SKIPPED.append(str(path.relative_to(ROOT)))
        return False
    html = path.read_text(encoding="utf-8")
    html = replace_block(html, "SITE-NAV-HEAD", head_html(crumbs), r"</head>", "before", path)
    html = replace_block(html, "SITE-NAV", nav_html(lang, current, crumbs), header_anchor, "after", path)
    if near:
        html = replace_block(html, "SITE-NAV-RELATED", related_html(lang, near), r"<footer", "before", path)
    g = guides_html(lang, RELATED_GUIDES[guides], html) if guides else None
    if g:
        html = replace_block(html, "SITE-NAV-GUIDES", g, r"<footer", "before", path)
    else:
        html = drop_block(html, "SITE-NAV-GUIDES")
    path.write_text(html, encoding="utf-8")
    return True


def crumbs_for(lang, key):
    """Home > [parent guide >] this guide."""
    home = (HOME[lang], href(lang, "/"))
    _, path, parent, short, long_ = GUIDE[key]
    label = (short or {}).get(lang) or nav_label(key, lang) or long_[lang]
    out = [home]
    if parent:
        pp = GUIDE[parent]
        out.append(((pp[3] or {}).get(lang) or nav_label(parent, lang) or pp[4][lang], href(lang, pp[1])))
    out.append((label, href(lang, path)))
    return out


def nav_label(key, lang):
    for k, _, lbl in NAV:
        if k == key:
            return lbl[lang]
    return None


def main():
    trails = json.loads((ROOT / "status.json").read_text())["trails"]
    coords = trail_coords()
    missing = [t["code"] for t in trails if t["code"] not in coords or not t.get("page")]
    if missing:
        sys.exit("FATAL: no coordinates or page for {}".format(missing))

    def nearest(t):
        others = [(o, km(coords[t["code"]], coords[o["code"]])) for o in trails if o["page"] != t["page"]]
        return sorted(others, key=lambda x: x[1])[:N_RELATED]

    nav_keys = {k for k, _, _ in NAV}
    n = 0
    for lang in LANGS:
        home = (HOME[lang], href(lang, "/"))   # the homepage is the trails board
        for t in trails:
            name = "{} {}".format(t["code"], t["name"])
            is_pr1 = t["page"] == "/pr1/"
            n += process(file_for(lang, t["page"]), lang, "pr1" if is_pr1 else None,
                         [home, (name, href(lang, t["page"]))], nearest(t),
                         guides="pr1" if is_pr1 else ("spoke-pr1" if t["code"] == "PR1.2" else "spoke"))
        n += process(file_for(lang, "/"), lang, "trails", None, guides="home")
        for key, p, *_ in GUIDES:
            if key == "pr1":
                continue   # a trail page, handled above
            n += process(file_for(lang, p), lang, key if key in nav_keys else None, crumbs_for(lang, key), guides=key)
    # English-only privacy page: nav bar only, no language switcher to anchor on.
    process(ROOT / "privacy" / "index.html", "en", None, None, header_anchor=r"<header>\n")
    print("site nav written to {} pages (+ privacy)".format(n))
    if SKIPPED:
        print("skipped {} missing page(s) -- re-run once they exist: {}".format(len(SKIPPED), ", ".join(SKIPPED)))


if __name__ == "__main__":
    main()
