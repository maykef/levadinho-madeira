"""Write the "Ask Levadinho on WhatsApp" block into every page (all 5 languages).

Levadinho (the bot in bot/) only works on WhatsApp, so every page hands the visitor
over with:
  - a tap-to-open wa.me link (all screens), pre-filled with
        "Olá Levadinho! 👋 #web-<tag>"
    where the per-page tag tells the bot's analytics which page converted
    (bot/brain.py treats any `web-[a-z0-9-]{1,40}` tag as a source, not a guide route);
  - an inline SVG QR code of the same link, shown only on wider screens (a desktop
    visitor scans it with the phone that has WhatsApp). Generated here with the
    `qrcode` library, so the page needs no external file.

Two marker-delimited blocks, replaced in place on every run (idempotent):

  LEVADINHO-CTA-HEAD  before </head>   the block's CSS
  LEVADINHO-CTA       in the body      the block + a GoatCounter click event

A page with no LEVADINHO-CTA markers gets the block just before the first of: the
"Nearby trails" block, the "More guides" block, <footer>. To place it elsewhere, put
empty markers there by hand; later runs keep that spot.

Tags: same tag in every language (the bot detects the language itself). Trail pages use
their code (web-pr6, web-pr1-2, ...); guide pages have fixed short tags (TAGS below).
Not added to privacy/ or the trails/ redirect stubs. Fails loud on a page it can't tag.

    python scripts/gen_cta.py
"""

