def page_lang_and_rel(path):
    rel = path.relative_to(ROOT).as_posix()
    first = rel.split("/")[0]
    if first in LANG_DIRS:
        return first, rel.split("/", 1)[1]
    return "en", rel


def tag_for(rel, html):
    if rel in TAGS:
        return TAGS[rel]
    m = re.search(r'id="statusCard"[^>]*data-trail="([^"]+)"', html)
    if m:
        return "web-" + m.group(1).lower().replace(".", "-")
    return None


def wa_url(tag):
    return "https://wa.me/{}?text={}".format(PHONE, urllib.parse.quote(GREETING.format(tag=tag), safe=""))


_QR = {}


def qr_svg(url, label):
    """A compact SVG: one <path> of horizontal runs of dark modules, with a 2-module quiet zone."""
    if url not in _QR:
        q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=2)
        q.add_data(url)
        q.make(fit=True)
        m = q.get_matrix()              # includes the border
        n = len(m)
        d = []
        for y, row in enumerate(m):
            x = 0
            while x < n:
                if row[x]:
                    x0 = x
                    while x < n and row[x]:
                        x += 1
                    d.append("M{} {}h{}v1h-{}z".format(x0, y, x - x0, x - x0))
                else:
                    x += 1
        _QR[url] = (n, "".join(d))
    n, d = _QR[url]
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" role="img" aria-label="{a}" shape-rendering="crispEdges">'
            '<rect width="{n}" height="{n}" fill="#fff"/><path fill="#16342A" d="{d}"/></svg>').format(n=n, a=label, d=d)


def block_html(lang, tag):
    T = TEXT[lang]
    url = wa_url(tag)
    href = url.replace("&", "&amp;")
    return (
        '<aside class="lvd-cta" aria-labelledby="lvd-cta-h">\n'
        '  <div>\n'
        '    <h2 id="lvd-cta-h">{h}</h2>\n'
        '    <p>{p}</p>\n'
        '    <a class="lvd-cta-btn" href="{href}" target="_blank" rel="noopener" data-tag="{tag}">{btn}</a>\n'
        '  </div>\n'
        '  <figure class="lvd-cta-qr">{svg}<figcaption>{cap}</figcaption></figure>\n'
        '</aside>\n'
        '<script>\n'
        '(function(){{var a=document.querySelector(".lvd-cta-btn");if(!a)return;\n'
        '  a.addEventListener("click",function(){{try{{var g=window.goatcounter;\n'
        '    if(g&&g.count)g.count({{path:"whatsapp-"+a.getAttribute("data-tag"),title:"Levadinho WhatsApp CTA",event:true}});}}catch(e){{}}}});}})();\n'
        '</script>'
    ).format(h=T["h"], p=T["p"], href=href, tag=tag, btn=T["btn"], svg=qr_svg(url, T["qr"]), cap=T["cap"])


def put(html, key, body, anchors, path):
    start, end = MARK[key]
    block = "{}\n{}\n{}".format(start, body, end)
    if start in html:
        return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, html, count=1, flags=re.S)
    for a in anchors:
        i = html.find(a)
        if i >= 0:
            return html[:i] + block + "\n" + html[i:]
    sys.exit("FATAL: no anchor for {} in {}".format(key, path))


def pages():
    for p in sorted(ROOT.rglob("*.html")):
        parts = p.relative_to(ROOT).parts
        if parts[0] in SKIP_TOP or p.name.startswith("google"):
            continue
        if len(parts) > 1 and parts[0] in LANG_DIRS and parts[1] in ("trails", "privacy"):
            continue
        yield p


def main():
    n, tags = 0, {}
    for p in pages():
        lang, rel = page_lang_and_rel(p)
        html = p.read_text(encoding="utf-8")
        tag = tag_for(rel, html)
        if not tag or not WEB_TAG.fullmatch(tag):
            sys.exit("FATAL: no WhatsApp tag for {} -- add it to TAGS".format(p.relative_to(ROOT)))
        if tags.setdefault((lang, tag), rel) != rel:
            sys.exit("FATAL: tag {} used by both {} and {}".format(tag, tags[(lang, tag)], rel))
        html = put(html, "LEVADINHO-CTA-HEAD", CSS, ["<!-- SITE-NAV-HEAD:START", "</head>"], p)
        html = put(html, "LEVADINHO-CTA", block_html(lang, tag),
                   ["<!-- SITE-NAV-RELATED:START", "<!-- SITE-NAV-GUIDES:START", "<footer"], p)
        p.write_text(html, encoding="utf-8")
        n += 1
    print("WhatsApp CTA written to {} pages ({} tags)".format(n, len({t for _, t in tags})))


if __name__ == "__main__":
    main()
